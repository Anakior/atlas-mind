export function t(key: string, ...args: unknown[]): string {
  const dict = STRINGS[LANG] || STRINGS.fr;
  let entry = dict[key];

  if (entry === undefined) entry = STRINGS.fr[key];

  if (entry === undefined) return key;

  return typeof entry === 'function' ? entry(...args) : entry;
}

// Static HTML labels via data-i18n / -title / -placeholder / -tip / -aria. Single source of
// truth = STRINGS; the FR text in the markup is only a fallback when JS is off.
export function applyStaticI18n(): void {
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n!);
  });
  document.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle!);
  });
  document.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder!);
  });
  document.querySelectorAll<HTMLElement>('[data-i18n-tip]').forEach((el) => {
    el.dataset.tip = t(el.dataset.i18nTip!);
  });
  document.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria!));
  });
}

applyStaticI18n();
